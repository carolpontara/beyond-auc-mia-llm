"""Membership inference scores for one federated run.

Higher score means "more likely a member" for every attack. All scores use the logit-scaled
confidence phi(x) = z_y - logsumexp_{j != y} z_j = log(p_y / (1 - p_y)), which is a strictly
decreasing function of the cross-entropy loss but does not saturate at zero loss, so strict
FPR thresholds are not degenerated by ties.
  loss        phi under the global model (loss attack, Yeom et al., 2018)
  refgap      phi(global) - phi(reference), the reference model being trained on disjoint
              population data (difficulty calibration, Watson et al., 2022)
  gradnorm    negative log norm of the per-sample gradient at the global model
  gradalign   server-side: largest cosine between the descent direction of the sample at
              the broadcast model w_{r-1} and the update returned by any client at round r
  trajectory  mean, over the global models of rounds 10, 20, ..., 100, of phi standardised
              with the reference population statistics of the same round
"""
import argparse
import os

import numpy as np
import torch
from torch import nn
from torch.func import functional_call, grad, vmap

from common import CHECKPOINT_ROUNDS, TRAJECTORY_EVERY, build_model, load_pool
from run_experiment import run_dir

CE = nn.CrossEntropyLoss(reduction="none")


def phi_from_logits(z, y):
    zy = z.gather(1, y[:, None])[:, 0]
    other = z.masked_fill(nn.functional.one_hot(y, z.shape[1]).bool(), float("-inf"))
    return zy - torch.logsumexp(other, dim=1)


def phi(model, X, y, bs=8192):
    out = []
    with torch.no_grad():
        for i in range(0, len(y), bs):
            out.append(phi_from_logits(model(X[i:i + bs]).double(), y[i:i + bs]))
    return torch.cat(out).numpy()


def grad_features(model, X, y, deltas=None, bs=1024):
    """Log per-sample gradient norm and, optionally, max cosine with client updates.

    The gradient of the cross-entropy equals (1 - p_y) times the gradient of
    sum_j e_j z_j with e_j = softmax_{k != y}(z)_j for j != y and e_y = -1, so the
    gradient is computed in that normalised form and its log norm is corrected by
    log(1 - p_y) = -softplus(phi), which avoids underflow for confident samples.
    """
    model = model.double()
    X = X.double()
    params = {k: v.detach() for k, v in model.named_parameters()}
    dn = None
    if deltas is not None:
        deltas = deltas.double()
        dn = deltas / deltas.norm(dim=1, keepdim=True).clamp_min(1e-300)

    def f(p, x, t):
        z = functional_call(model, p, (x[None],))[0]
        onehot = torch.arange(z.shape[0]) == t
        e = torch.softmax(z.masked_fill(onehot, float("-inf")), 0).masked_fill(onehot, -1.0).detach()
        return (e * z).sum()

    g_fn = vmap(grad(f), in_dims=(None, 0, 0))
    lognorm, align = [], []
    for i in range(0, len(y), bs):
        xb, yb = X[i:i + bs], y[i:i + bs]
        g = g_fn(params, xb, yb)
        G = torch.cat([g[k].reshape(len(g[k]), -1) for k in params], dim=1)
        n = G.norm(dim=1).clamp_min(1e-300)
        with torch.no_grad():
            ph = phi_from_logits(model(xb), yb)
        lognorm.append(n.log() - nn.functional.softplus(ph))
        if dn is not None:
            align.append(((-G) @ dn.T / n[:, None]).max(dim=1).values)
    return torch.cat(lognorm).numpy(), (torch.cat(align).numpy() if dn is not None else None)


def reference_model(work, dataset, seed, epochs=100, lr=0.05, bs=32):
    path = os.path.join(work, "reference", f"{dataset}_s{seed}.pt")
    pool = os.path.join(work, "data", f"{dataset}.npz")
    model = build_model(pool)
    if os.path.exists(path):
        model.load_state_dict(torch.load(path))
        return model
    X, y, split = load_pool(pool)
    Xr, yr = torch.from_numpy(X[split == "reference"]), torch.from_numpy(y[split == "reference"])
    torch.manual_seed(10_000 + seed)
    model = build_model(pool)
    opt = torch.optim.SGD(model.parameters(), lr=lr)
    gen = torch.Generator().manual_seed(20_000 + seed)
    ce = nn.CrossEntropyLoss()
    for _ in range(epochs):
        perm = torch.randperm(len(yr), generator=gen)
        for i in range(0, len(yr), bs):
            b = perm[i:i + bs]
            loss = ce(model(Xr[b]), yr[b])
            opt.zero_grad()
            loss.backward()
            opt.step()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    torch.save(model.state_dict(), path)
    return model


def load_global(pool, d, r):
    m = build_model(pool)
    m.load_state_dict(torch.load(os.path.join(d, f"global_r{r}.pt")))
    return m


def client_deltas(d, r, keys):
    u = np.load(os.path.join(d, f"updates_r{r}.npz"))
    sent = np.concatenate([u[f"sent/{k}"].reshape(-1) for k in keys])
    clients = sorted({n.split("/")[0] for n in u.files if n.startswith("client")}, key=lambda s: int(s[6:]))
    D = np.stack([np.concatenate([u[f"{c}/{k}"].reshape(-1) for k in keys]) - sent for c in clients])
    params = {k: torch.from_numpy(u[f"sent/{k}"]) for k in keys}
    return torch.from_numpy(D), params


def score_run(work, dataset, alpha, agg, seed, rounds=100):
    torch.set_num_threads(2)
    d = run_dir(work, dataset, alpha, agg, seed)
    pool = os.path.join(work, "data", f"{dataset}.npz")
    X, y, split = load_pool(pool)
    ev = np.flatnonzero((split == "member") | (split == "nonmember"))
    ref = np.flatnonzero(split == "reference")
    Xe, ye = torch.from_numpy(X[ev]), torch.from_numpy(y[ev])
    Xr, yr = torch.from_numpy(X[ref]), torch.from_numpy(y[ref])
    refm = reference_model(work, dataset, seed)
    ref_phi = phi(refm, Xe, ye)
    out = {"eval_idx": ev, "is_member": (split[ev] == "member").astype(np.int8)}
    keys = [k for k, _ in build_model(pool).named_parameters()]
    for r in CHECKPOINT_ROUNDS:
        if r > rounds:
            continue
        g = load_global(pool, d, r)
        pe = phi(g, Xe, ye)
        out[f"loss@{r}"] = pe
        out[f"refgap@{r}"] = pe - ref_phi
        gn, _ = grad_features(g, Xe, ye)
        out[f"gradnorm@{r}"] = -gn
        D, sent = client_deltas(d, r, keys)
        prev = build_model(pool)
        prev.load_state_dict(sent)
        _, ga = grad_features(prev, Xe, ye, deltas=D)
        out[f"gradalign@{r}"] = ga
    zs = []
    for r in range(TRAJECTORY_EVERY, rounds + 1, TRAJECTORY_EVERY):
        g = load_global(pool, d, r)
        pr = phi(g, Xr, yr)
        zs.append((phi(g, Xe, ye) - pr.mean()) / (pr.std() + 1e-12))
    out[f"trajectory@{rounds}"] = np.mean(zs, axis=0)
    path = os.path.join(work, "scores", dataset, f"a{alpha}", agg, f"s{seed}.npz")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    np.savez_compressed(path, **out)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default=os.path.expanduser("~/fedids_work"))
    ap.add_argument("--dataset", default="cicids2017")
    ap.add_argument("--alpha", type=float, default=0.5)
    ap.add_argument("--agg", default="fedavg")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--rounds", type=int, default=100)
    a = ap.parse_args()
    print(score_run(a.work, a.dataset, a.alpha, a.agg, a.seed, a.rounds))


if __name__ == "__main__":
    main()
